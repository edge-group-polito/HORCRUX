// ============================================================================
// Falcon modular arithmetic operations
// ============================================================================

uint32_t mq_add_sw(uint32_t x, uint32_t y) {
    uint32_t d = x + y - FALCON_Q;
    d += FALCON_Q & -(d >> 31);
    return d;
}

uint32_t mq_sub_sw(uint32_t x, uint32_t y) {
    uint32_t d = x - y;
    d += FALCON_Q & -(d >> 31);
    return d;
}

