// ============================================================================
// Software NTT implementation for Falcon (mod q=12289)
// ============================================================================

void mq_NTT_sw(uint16_t *a, unsigned logn) {
    size_t n = (size_t)1 << logn;
    size_t t = n;

    for (size_t m = 1; m < n; m <<= 1) {
        size_t ht = t >> 1;
        for (size_t i = 0, j1 = 0; i < m; i++, j1 += t) {
            uint32_t s = falcon_GMb_16[m + i];
            size_t j2 = j1 + ht;
            for (size_t j = j1; j < j2; j++) {
                uint32_t u = a[j];
                uint32_t v = mq_montymul_sw(a[j + ht], s);
                a[j] = (uint16_t)mq_add_sw(u, v);
                a[j + ht] = (uint16_t)mq_sub_sw(u, v);
            }
        }
        t = ht;
    }
}

// ============================================================================
// Software iNTT implementation for Falcon (mod q=12289)
// ============================================================================

void mq_iNTT_sw(uint16_t *a, unsigned logn) {
    size_t n = (size_t)1 << logn;
    size_t t = 1;
    size_t m = n;

    while (m > 1) {
        size_t hm = m >> 1;
        size_t dt = t << 1;
        for (size_t i = 0, j1 = 0; i < hm; i++, j1 += dt) {
            uint32_t s = falcon_iGMb_16[hm + i];
            size_t j2 = j1 + t;
            for (size_t j = j1; j < j2; j++) {
                uint32_t u = a[j];
                uint32_t v = a[j + t];
                a[j] = (uint16_t)mq_add_sw(u, v);
                uint32_t w = mq_sub_sw(u, v);
                a[j + t] = (uint16_t)mq_montymul_sw(w, s);
            }
        }
        t = dt;
        m = hm;
    }

    // Divide by n (using Montgomery multiplication)
    uint32_t ni = FALCON_R;
    for (size_t i = n; i > 1; i >>= 1) {
        ni += FALCON_Q & -(ni & 1);
        ni = ni >> 1;
    }

    for (size_t i = 0; i < n; i++) {
        a[i] = (uint16_t)mq_montymul_sw(a[i], ni);
    }
}

