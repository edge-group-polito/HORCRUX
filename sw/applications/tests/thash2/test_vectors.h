/*
 * Test vectors for OP_THASH2 (thash with 2 block input)
 * 
 * Used for Merkle tree node hashing in compute_root() and treehashx1().
 * These are deterministic test inputs.
 */

/* ========================================================================
 * Test Context: SPHINCS+ signing context
 * ======================================================================== */

/* pub_seed: 16 bytes */
static const uint8_t tv_pub_seed[SPX_N] = {
    0x01, 0x23, 0x45, 0x67, 0x89, 0xAB, 0xCD, 0xEF,
    0xFE, 0xDC, 0xBA, 0x98, 0x76, 0x54, 0x32, 0x10
};

/* sk_seed: 16 bytes (not used for thash) */
static const uint8_t tv_sk_seed[SPX_N] = {
    0xDE, 0xAD, 0xBE, 0xEF, 0xCA, 0xFE, 0xBA, 0xBE,
    0x12, 0x34, 0x56, 0x78, 0x9A, 0xBC, 0xDE, 0xF0
};

/* ========================================================================
 * Test Vector 1: thash with 2 blocks (Merkle tree internal node)
 * ======================================================================== */

/* SPHINCS+ address for tree hashing: type = HASHTREE */
static const uint8_t tv_addr_tree[SPX_ADDR_BYTES] = {
    0x00, 0x00, 0x00, 0x01,  /* layer = 1 */
    0x00, 0x00, 0x00, 0x00,
    0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x00, 0x02,  /* tree = 2 */
    0x00, 0x00, 0x00, 0x02,  /* type = HASHTREE at byte 19 */
    0x00, 0x00, 0x00, 0x00,  /* keypair addr */
    0x00, 0x00, 0x00, 0x03,  /* tree height = 3 at byte 27 */
    0x00, 0x00, 0x00, 0x05   /* tree index = 5 at bytes 28-31 */
};

/* Input: 2 blocks = 32 bytes (left child || right child) */
static const uint8_t tv_thash2_input[THASH2_INPUT_BYTES] = {
    /* Left child (16 bytes) */
    0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF, 0x00, 0x11,
    0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88, 0x99,
    /* Right child (16 bytes) */
    0x11, 0x22, 0x33, 0x44, 0x55, 0x66, 0x77, 0x88,
    0x99, 0xAA, 0xBB, 0xCC, 0xDD, 0xEE, 0xFF, 0x00
};

